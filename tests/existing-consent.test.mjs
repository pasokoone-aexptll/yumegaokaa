import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {randomUUID} from 'node:crypto';
import pg from 'pg';
import {gatewayAuthorizer} from '../scripts/lib/gateway-authorize.mjs';
test('existing consent: fail closed, actual checkbox, retry, privacy and withdrawal',async()=>{
 const originalFetch=globalThis.fetch;
 const db=new pg.Client({connectionString:'postgresql://postgres:postgres@127.0.0.1:54322/postgres'});await db.connect();
 try {await db.query('begin');
 for(const n of ['202611250058_registration_declaration.sql','202611250060_existing_member_consent.sql']) await db.query(readFileSync('supabase/migrations/'+n,'utf8').replace(/^begin;/,'').replace(/commit;\s*$/,''));
 const uid=randomUUID(),sid=randomUUID();await db.query('insert into auth.users(id) values($1)',[uid]);await db.query('insert into auth.sessions(id,user_id) values($1,$2)',[sid,uid]);await db.query('insert into app_private.members(account_id) values($1)',[uid]);
 await db.query("select set_config('request.jwt.claims',$1,true)",[JSON.stringify({sub:uid,session_id:sid,role:'authenticated'})]);
 const rpc=async(op,p={})=>{await db.query('set local role authenticated');const r=await db.query('select public.street_api($1,$2) r',[op,p]);await db.query('reset role');return r.rows[0].r;};
 const reject=async(fn,re)=>{await db.query('savepoint check_failure');await assert.rejects(fn,re);await db.query('rollback to savepoint check_failure');await db.query('reset role');};
 const street=randomUUID();await db.query("insert into app_private.streets(id,name) values($1,'consent test')",[street]);
 globalThis.fetch=async()=>({ok:true,json:async()=>({id:uid})});
 const token='header.'+Buffer.from(JSON.stringify({sub:uid,session_id:sid,role:'authenticated'})).toString('base64url')+'.test';
 const authorize=gatewayAuthorizer({apiURL:'https://example.test',publishableKey:'test',db,streetId:street});
 assert.equal(await authorize(token),null);
 assert.equal((await rpc('account_access')).status,'consent_required');
 await reject(()=>rpc('profile_get'),/membership_required/);
 assert.equal((await db.query('select public.avatar_member() b')).rows[0].b,false);
 const value={age_band:'13_17',guardian_declared:true,terms_accepted:true,policy_version:'2026-11-25-v1'};
 for(const p of [{...value,terms_accepted:false},{...value,terms_accepted:'true'},{...value,guardian_declared:false},{...value,age_band:'under_13'}]) await reject(()=>rpc('consent_accept',p),/invalid_input/);
 await reject(()=>rpc('consent_accept',{...value,policy_version:'old'}),/conflict/);
 assert.equal((await rpc('consent_accept',value)).accepted,true);
 assert.equal((await rpc('account_access')).status,'active');
 assert.equal((await authorize(token)).accountId,uid);
 assert.equal((await db.query('select public.avatar_member() b')).rows[0].b,true);
 const newcomer=randomUUID(),newSession=randomUUID(),invite=randomUUID();
 await db.query('insert into auth.users(id) values($1)',[newcomer]);await db.query('insert into auth.sessions(id,user_id) values($1,$2)',[newSession,newcomer]);
 await db.query("insert into app_private.invitations(issuer,code_hash) values($1,sha256(convert_to($2,'UTF8')))",[uid,invite]);
 await db.query("select set_config('request.jwt.claims',$1,true)",[JSON.stringify({sub:newcomer,session_id:newSession,role:'authenticated'})]);
 await reject(()=>rpc('invite_accept',{...value,code:invite,terms_accepted:false}),/invalid_input/);
 assert.equal((await rpc('invite_accept',{...value,code:invite})).accepted,true);
 assert.equal((await rpc('account_access')).status,'active');
 await db.query("select set_config('request.jwt.claims',$1,true)",[JSON.stringify({sub:uid,session_id:sid,role:'authenticated'})]);
 const record=(await db.query('select * from app_private.registration_declarations where account_id=$1',[uid])).rows[0];
 await rpc('consent_accept',value);assert.deepEqual((await db.query('select * from app_private.registration_declarations where account_id=$1',[uid])).rows[0],record);
 await db.query("update app_private.registration_policy set version='next'");assert.equal((await rpc('account_access')).status,'consent_required');
 await rpc('consent_accept',{...value,age_band:'18_plus',guardian_declared:false,policy_version:'next'});
 await db.query('update app_private.members set active=false,withdrawn_at=now() where account_id=$1',[uid]);
 assert.equal((await db.query('select count(*)::int n from app_private.registration_declarations where account_id=$1',[uid])).rows[0].n,0);
 await reject(()=>rpc('consent_accept',{...value,policy_version:'next'}),/membership_required/);
 }finally{globalThis.fetch=originalFetch;await db.query('rollback');await db.end();}
});
